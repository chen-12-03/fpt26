#!/usr/bin/env python3
"""Generate paper macros from the independent final-kernel reevaluation."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


MODEL_SPECS = (
    ("DeepSeek", "deepseek", "DeepSeek V4 Pro"),
    ("QwenThreeFive", "qwen3.5-122b-a10b", "Qwen3.5-122B-A10B"),
    ("QwenThreeSix", "qwen3.6-27b", "Qwen3.6-27B"),
)


def command(name: str, value: str) -> str:
    return rf"\newcommand{{\{name}}}{{{value}}}"


def mean(values: list[float]) -> float:
    if not values:
        raise ValueError("cannot compute a mean over an empty list")
    return sum(values) / len(values)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        type=Path,
        default=(
            repo_root
            / "technical-paper/evidence/track_a_150_reevaluation_summary.json"
        ),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=repo_root / "technical-paper/evaluator_results_generated.tex",
    )
    args = parser.parse_args()

    with args.input.open(encoding="utf-8") as handle:
        report = json.load(handle)

    if report.get("schema_version") != 1:
        raise ValueError("unsupported reevaluation summary schema")
    rows = report["per_task"]
    if len(rows) != 450:
        raise ValueError(f"expected 450 task records, found {len(rows)}")

    source = args.input
    try:
        source = args.input.resolve().relative_to(repo_root.resolve())
    except ValueError:
        pass
    lines = [
        "% Generated by technical-paper/scripts/update_evaluator_results.py.",
        f"% Source: {source}",
        "% Reference means use valid scores; missing metrics remain unavailable.",
    ]

    total_evaluated = 0
    total_hidden_correct = 0
    model_task_scores: dict[str, dict[str, float]] = {}
    for prefix, model_key, display_name in MODEL_SPECS:
        model_rows = [row for row in rows if row["model"] == model_key]
        if len(model_rows) != 150:
            raise ValueError(
                f"{model_key}: expected 150 task records, found {len(model_rows)}"
            )
        public_count = sum(bool(row["public_gate_completed"]) for row in model_rows)
        evaluated_count = sum(row["evaluator_report"] is not None for row in model_rows)
        hidden_count = sum(row["hidden_correct"] is True for row in model_rows)
        if public_count != evaluated_count or hidden_count != evaluated_count:
            raise ValueError(
                f"{model_key}: public/evaluated/hidden counts differ: "
                f"{public_count}/{evaluated_count}/{hidden_count}"
            )
        if any(
            row["grading_source"] != "hidden"
            for row in model_rows
            if row["evaluator_report"] is not None
        ):
            raise ValueError(f"{model_key}: evaluator report lacks hidden grading")

        valid_scores = [
            float(row["reference_anchored_score"])
            for row in model_rows
            if row["reference_score_valid"] is True
        ]
        qor_rows = [row for row in model_rows if row["category"] == "qor_optimization"]
        qor_scores = [
            float(row["reference_anchored_score"])
            for row in qor_rows
            if row["reference_score_valid"] is True
        ]
        if len(qor_rows) != 25 or len(qor_scores) != 25:
            raise ValueError(f"{model_key}: QoR-25 reference slice is incomplete")

        model_task_scores[model_key] = {
            row["task_id"]: float(row["reference_anchored_score"])
            for row in model_rows
            if row["reference_score_valid"] is True
        }
        total_evaluated += evaluated_count
        total_hidden_correct += hidden_count
        lines.extend(
            [
                "",
                f"% --- {display_name} ---",
                command(f"{prefix}EvaluatorReportCount", str(evaluated_count)),
                command(f"{prefix}HiddenCorrectCount", str(hidden_count)),
                command(f"{prefix}ReferenceScoreableCount", str(len(valid_scores))),
                command(
                    f"{prefix}ReferenceUnavailableCount",
                    str(150 - len(valid_scores)),
                ),
                command(f"{prefix}ReferenceMeanScoreable", f"{mean(valid_scores):.2f}"),
                command(f"{prefix}ReferenceQorScoreableCount", str(len(qor_scores))),
                command(f"{prefix}ReferenceQorMean", f"{mean(qor_scores):.2f}"),
            ]
        )

    common_tasks = set.intersection(
        *(set(scores) for scores in model_task_scores.values())
    )
    hash_match_count = sum(
        row["kernel_sha256_matches_submission_evidence"] is True for row in rows
    )
    if hash_match_count != 450:
        raise ValueError(f"expected 450 matching kernel hashes, found {hash_match_count}")

    lines.extend(
        [
            "",
            "% --- Aggregate and comparable subsets ---",
            command("IndependentEvaluatedCount", str(total_evaluated)),
            command("IndependentHiddenCorrectCount", str(total_hidden_correct)),
            command("FinalKernelHashMatchCount", str(hash_match_count)),
            command("CommonReferenceTaskCount", str(len(common_tasks))),
        ]
    )
    for prefix, model_key, _ in MODEL_SPECS:
        common_scores = [model_task_scores[model_key][task] for task in common_tasks]
        lines.append(command(f"{prefix}CommonReferenceMean", f"{mean(common_scores):.2f}"))

    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
